import * as THREE from 'three';
import type { Shape } from './species';

// Bird local frame: +Z forward (beak), +Y up, wings along ±X.

export const PART = {
  BODY: 0,
  WING_TOP: 1,
  WING_BOTTOM: 2,
  TAIL_TOP: 3,
  TAIL_BOTTOM: 4,
  BEAK: 5,
  LEGS: 6,
  EYE: 7,
} as const;

export interface BirdPose {
  flap: number; // shoulder elevation (rad, +up)
  wrist: number; // extra hand elevation (rad)
  fold: number; // 0 spread .. 1 folded against body
  sweep: number; // arm sweep-back (rad)
  twist: number; // feather pitch along span (rad)
  tailSpread: number; // 0 closed .. 1 fanned
  tailPitch: number; // rad
  tailTwist: number; // rad
  legsDown: number; // 0 tucked/trailing .. 1 lowered for landing
  headYaw: number;
  bank: number; // used to bias left/right wing dihedral (rad)
}

export function defaultPose(): BirdPose {
  return { flap: 0, wrist: 0, fold: 0, sweep: 0, twist: 0, tailSpread: 0.3, tailPitch: 0, tailTwist: 0, legsDown: 0, headYaw: 0, bank: 0 };
}

class Builder {
  pos: number[] = [];
  uv: number[] = [];
  part: number[] = [];
  idx: number[] = [];
  // Deformation metadata: kind 0 static, 1 wing, 2 tail, 3 legs, 4 head; side ±1; span parameter s.
  kind: number[] = [];
  side: number[] = [];
  span: number[] = [];

  get count() {
    return this.pos.length / 3;
  }

  vert(x: number, y: number, z: number, u: number, v: number, part: number, kind = 0, side = 0, span = 0) {
    this.pos.push(x, y, z);
    this.uv.push(u, v);
    this.part.push(part);
    this.kind.push(kind);
    this.side.push(side);
    this.span.push(span);
    return this.count - 1;
  }

  /** Adds a grid of (nu+1)*(nv+1) vertices generated by fn and triangulates it. */
  grid(nu: number, nv: number, fn: (u: number, v: number) => void, flip = false) {
    const start = this.count;
    for (let j = 0; j <= nv; j++) for (let i = 0; i <= nu; i++) fn(i / nu, j / nv);
    for (let j = 0; j < nv; j++) {
      for (let i = 0; i < nu; i++) {
        const a = start + j * (nu + 1) + i;
        const b = a + 1;
        const c = a + nu + 1;
        const d = c + 1;
        if (flip) this.idx.push(a, b, c, b, d, c);
        else this.idx.push(a, c, b, b, c, d);
      }
    }
  }
}

function smooth(e0: number, e1: number, x: number) {
  const t = Math.min(1, Math.max(0, (x - e0) / (e1 - e0)));
  return t * t * (3 - 2 * t);
}

interface Ring {
  z: number;
  y: number;
  rx: number;
  ry: number;
}

/** Torso + neck + head profile from tail base to beak base. */
function bodyProfile(s: Shape): { rings: Ring[]; headT: number; headZ: number; headY: number } {
  const w = s.bodyWidth / 2;
  const h = s.bodyDepth / 2;
  const torso = s.length - s.tailLen - s.neckLen - s.headSize * 1.6 - s.beakLen * 0.4;
  const tl = Math.max(torso, s.length * 0.3);
  const z0 = -tl * 0.55;
  const hs = s.headSize / 2;
  const longNeck = s.neckLen > 0.1;
  const keys: [number, number, number, number][] = [
    // z, y, rx, ry
    [z0, 0.02 * h, w * 0.32, h * 0.25],
    [z0 + tl * 0.18, 0.0, w * 0.75, h * 0.7],
    [z0 + tl * 0.45, -0.05 * h, w * 1.0, h * 1.0],
    [z0 + tl * 0.72, -0.02 * h, w * 0.95, h * 0.98],
    [z0 + tl * 0.95, 0.08 * h, w * 0.62, h * 0.66],
  ];
  let z = z0 + tl * 0.95;
  let y = 0.08 * h;
  if (longNeck) {
    const n = s.neckLen;
    keys.push([z + n * 0.3, y + 0.02, hs * 0.85, hs * 0.9]);
    keys.push([z + n * 0.7, y + 0.03, hs * 0.7, hs * 0.75]);
    z += n;
    y += 0.035;
  } else {
    z += s.neckLen + hs * 0.4;
    y += h * 0.25;
    keys.push([z, y, Math.max(hs * 1.0, w * 0.5), Math.max(hs * 1.0, h * 0.55)]);
  }
  const headT0 = keys.length;
  keys.push([z + hs * 0.6, y + hs * 0.15, hs * 1.05, hs * 1.0]);
  keys.push([z + hs * 1.25, y + hs * 0.2, hs * 0.98, hs * 0.95]);
  keys.push([z + hs * 1.8, y + hs * 0.05, hs * 0.66, hs * 0.62]);
  keys.push([z + hs * 2.1, y - hs * 0.05, hs * 0.32, hs * 0.34]);
  const rings: Ring[] = keys.map(([kz, ky, rx, ry]) => ({ z: kz, y: ky, rx, ry }));
  return { rings, headT: headT0 / (keys.length - 1), headZ: z + hs * 1.1, headY: y + hs * 0.2 };
}

function catmull(rings: Ring[], t: number): Ring {
  const n = rings.length - 1;
  const f = t * n;
  const i = Math.min(n - 1, Math.floor(f));
  const u = f - i;
  const p0 = rings[Math.max(0, i - 1)];
  const p1 = rings[i];
  const p2 = rings[i + 1];
  const p3 = rings[Math.min(n, i + 2)];
  const cr = (a: number, b: number, c: number, d: number) =>
    0.5 * (2 * b + (-a + c) * u + (2 * a - 5 * b + 4 * c - d) * u * u + (-a + 3 * b - 3 * c + d) * u * u * u);
  return {
    z: cr(p0.z, p1.z, p2.z, p3.z),
    y: cr(p0.y, p1.y, p2.y, p3.y),
    rx: Math.max(0.001, cr(p0.rx, p1.rx, p2.rx, p3.rx)),
    ry: Math.max(0.001, cr(p0.ry, p1.ry, p2.ry, p3.ry)),
  };
}

export interface WingLayout {
  rootX: number;
  semi: number;
  rootChord: number;
  wristS: number;
  shoulderZ: number;
  wristZ: number;
}

export class BirdModel {
  readonly geometry: THREE.BufferGeometry;
  readonly mesh: THREE.Mesh;
  readonly layout: WingLayout;
  readonly headT: number;
  readonly fingerStart: number;
  private rest: Float32Array;
  private kind: Uint8Array;
  private side: Int8Array;
  private span: Float32Array;
  private posAttr: THREE.BufferAttribute;
  private tailBaseZ: number;
  private tailBaseY: number;
  private legPivot: THREE.Vector3;
  private headPivot: THREE.Vector3;
  private tmp = new THREE.Vector3();

  constructor(readonly shape: Shape, material: THREE.Material) {
    const b = new Builder();
    const s = shape;
    const prof = bodyProfile(s);
    this.headT = prof.headT;

    // --- Body loft -------------------------------------------------------------
    const RINGS = 40;
    const SEG = 22;
    const ringsEval: Ring[] = [];
    for (let i = 0; i <= RINGS; i++) ringsEval.push(catmull(prof.rings, i / RINGS));
    b.grid(SEG, RINGS, (u, v) => {
      const r = ringsEval[Math.round(v * RINGS)];
      const a = u * Math.PI * 2;
      // Flatten the belly slightly and keep the back rounded.
      const yy = Math.cos(a) * r.ry * (Math.cos(a) < 0 ? 0.92 : 1);
      const isHead = v >= prof.headT - 0.02;
      b.vert(Math.sin(a) * r.rx, r.y + yy, r.z, v, u, PART.BODY, isHead ? 4 : 0);
    });
    const tailBase = ringsEval[1];
    this.tailBaseZ = tailBase.z + 0.01;
    this.tailBaseY = tailBase.y + 0.005;
    const headTip = ringsEval[RINGS];
    this.headPivot = new THREE.Vector3(0, prof.headY, prof.headZ - s.headSize * 0.6);

    // --- Eyes -------------------------------------------------------------------
    const eyeR = s.disk ? s.headSize * 0.09 : s.headSize * 0.1;
    for (const sideSign of [-1, 1]) {
      const ez = prof.headZ + s.headSize * (s.disk ? 0.38 : 0.12);
      const ey = prof.headY + s.headSize * 0.08;
      const ex = sideSign * s.headSize * (s.disk ? 0.24 : 0.43);
      b.grid(8, 6, (u, v) => {
        const th = u * Math.PI * 2;
        const ph = v * Math.PI;
        b.vert(ex + Math.sin(ph) * Math.cos(th) * eyeR, ey + Math.cos(ph) * eyeR, ez + Math.sin(ph) * Math.sin(th) * eyeR, u, v, PART.EYE, 4);
      });
    }

    // --- Owl / harrier facial disk -------------------------------------------------
    if (s.disk) {
      const dz = prof.headZ + s.headSize * 0.42;
      const dr = s.headSize * 0.55;
      b.grid(16, 4, (u, v) => {
        const a = u * Math.PI * 2;
        const r = v * dr * (1 - 0.15 * Math.cos(a * 2));
        const cup = (v * v) * s.headSize * 0.14;
        b.vert(Math.cos(a) * r, prof.headY + Math.sin(a) * r * 1.05 - s.headSize * 0.04, dz - cup + 0.002, 0.95 + v * 0.05, u, PART.BODY, 4);
      }, true);
    }

    // --- Beak ------------------------------------------------------------------------
    this.buildBeak(b, s, headTip);

    // --- Wings -------------------------------------------------------------------------
    const semi = s.wingspan / 2 - s.bodyWidth * 0.4;
    const rootX = s.bodyWidth * 0.32;
    const rootChord = s.chord * (s.wingspan / 2);
    const shoulderZ = -0.02 + (s.length - s.tailLen) * 0.05;
    const wristS = s.tip === 'pointed' ? 0.42 : 0.47;
    const fingerStart = s.fingers > 0 ? 1 - s.fingerLen : 1;
    this.fingerStart = fingerStart;

    const chordAt = (t: number) => {
      if (s.tip === 'pointed') return rootChord * Math.max(0.05, 1 - s.taper * Math.pow(t, 1.15));
      if (s.tip === 'rounded') return rootChord * Math.max(0.12, Math.sqrt(Math.max(0, 1 - Math.pow(t, 2.6))) * (1 - 0.1 * t));
      return rootChord * (1 - s.taper * 0.5 * t);
    };
    const leAt = (t: number) => {
      const bulge = 0.12 * rootChord * Math.sin(Math.PI * Math.min(1, t / (wristS * 1.1)));
      return shoulderZ + rootChord * 0.3 + bulge - Math.pow(t, 1.4) * Math.tan(s.sweep) * semi * 0.6;
    };
    const wristZ = leAt(wristS) - chordAt(wristS) * 0.2;
    this.layout = { rootX, semi, rootChord, wristS, shoulderZ, wristZ };

    for (const sideSign of [-1, 1]) {
      for (const top of [true, false]) {
        const part = top ? PART.WING_TOP : PART.WING_BOTTOM;
        const NS = 28;
        const NC = 12;
        b.grid(
          NS,
          NC,
          (u, v) => {
            const t = u * fingerStart;
            const c = chordAt(t);
            const zle = leAt(t);
            const z = zle - v * c;
            const camber = Math.sin(Math.PI * v) * c * 0.07 * (1 - 0.6 * t);
            const thick = Math.sin(Math.PI * Math.sqrt(v)) * c * 0.035 * (1 - t);
            const y = camber + (top ? thick : -thick * 0.3);
            const x = sideSign * (rootX + t * semi);
            b.vert(x, y, z, t, v, part, 1, sideSign, t);
          },
          (sideSign > 0) !== top,
        );

        if (s.fingers > 0) {
          // Separated primary "fingers" of soaring birds.
          const n = s.fingers;
          const cHand = chordAt(fingerStart);
          const zleHand = leAt(fingerStart);
          for (let f = 0; f < n; f++) {
            const fr = (f + 0.5) / n;
            const baseZ = zleHand - fr * cHand * 0.95;
            const len = s.fingerLen * semi * (1.08 - 0.5 * Math.pow(Math.abs(fr - 0.35) * 1.6, 2)) * (f === 0 ? 0.82 : 1);
            const width = (cHand / n) * 1.05;
            const fan = (fr - 0.3) * 0.75; // leading fingers point forward
            b.grid(
              6,
              2,
              (u, v) => {
                const along = u * len;
                const wdt = width * (1 - 0.62 * u) * (v - 0.5);
                const dx = Math.cos(fan) * along;
                const dz = -Math.sin(fan) * along;
                const curl = u * u * len * 0.12;
                const x = sideSign * (rootX + fingerStart * semi - 0.01 + dx);
                const z = baseZ + dz + wdt;
                const sp = fingerStart + (u * len) / semi;
                b.vert(x, curl + (top ? 0.002 : -0.001), z, sp, 0.35 + fr * 0.65 + (v - 0.5) * 0.1, part, 1, sideSign, sp);
              },
              (sideSign > 0) !== top,
            );
          }
        }
      }
    }

    // --- Tail fan ------------------------------------------------------------------------
    for (const top of [true, false]) {
      const part = top ? PART.TAIL_TOP : PART.TAIL_BOTTOM;
      b.grid(
        10,
        5,
        (u, v) => {
          const across = u * 2 - 1;
          let len = s.tailLen;
          if (s.tail === 'wedge') len *= 1 - 0.25 * Math.abs(across);
          if (s.tail === 'notched') len *= 1 + 0.08 * Math.abs(across);
          if (s.tail === 'fan') len *= 1 - 0.1 * across * across;
          const r = v * len;
          const halfW = (s.tailWidth / 2) * (0.45 + 0.55 * v);
          const x = across * halfW;
          const z = this.tailBaseZ - r;
          const y = this.tailBaseY + (top ? 0.002 : -0.002) - v * 0.004;
          b.vert(x, y, z, u, v, part, 2, 0, across);
        },
        !top,
      );
    }

    // --- Legs -------------------------------------------------------------------------------
    this.legPivot = new THREE.Vector3(0, -s.bodyDepth * 0.35, ringsEval[8].z);
    for (const sideSign of [-1, 1]) {
      const lx = sideSign * s.bodyWidth * 0.18;
      const r = Math.max(0.004, s.legLen * 0.03);
      const trailing = s.legs === 'trailing';
      b.grid(5, 6, (u, v) => {
        const a = u * Math.PI * 2;
        const len = trailing ? s.legLen : s.legLen * 0.55;
        const rr = r * (v > 0.85 ? 0.7 : 1);
        b.vert(lx + Math.cos(a) * rr, this.legPivot.y + Math.sin(a) * rr, this.legPivot.z - v * len, u, v, PART.LEGS, 3, sideSign, v);
      });
      // Simple three-toed foot.
      for (let toe = -1; toe <= 1; toe++) {
        const len = trailing ? s.legLen : s.legLen * 0.55;
        const tz = this.legPivot.z - len;
        b.grid(3, 2, (u, v) => {
          const a = u * Math.PI * 2;
          const tl = s.legLen * (trailing ? 0.12 : 0.2) * v;
          b.vert(lx + toe * tl * 0.5 + Math.cos(a) * r * 0.6, this.legPivot.y + Math.sin(a) * r * 0.6, tz - tl, u, 1, PART.LEGS, 3, sideSign, 1 + v * 0.2);
        });
      }
    }

    const geo = new THREE.BufferGeometry();
    this.rest = new Float32Array(b.pos);
    this.posAttr = new THREE.BufferAttribute(new Float32Array(b.pos), 3);
    this.posAttr.setUsage(THREE.DynamicDrawUsage);
    geo.setAttribute('position', this.posAttr);
    geo.setAttribute('aUv', new THREE.Float32BufferAttribute(b.uv, 2));
    geo.setAttribute('aPart', new THREE.Float32BufferAttribute(b.part, 1));
    geo.setIndex(b.idx);
    geo.computeVertexNormals();
    geo.computeBoundingSphere();
    this.kind = new Uint8Array(b.kind);
    this.side = new Int8Array(b.side);
    this.span = new Float32Array(b.span);
    this.geometry = geo;
    this.mesh = new THREE.Mesh(geo, material);
    this.mesh.frustumCulled = false;
  }

  private buildBeak(b: Builder, s: Shape, tip: Ring) {
    const L = s.beakLen;
    const z0 = tip.z - s.headSize * 0.18;
    const y0 = tip.y - s.headSize * 0.03;
    const baseR = s.headSize * (s.beak === 'goose' || s.beak === 'pelican' ? 0.36 : s.beak === 'spear' ? 0.22 : 0.3);
    b.grid(10, 12, (u, v) => {
      const a = u * Math.PI * 2;
      let rx = baseR * (1 - v * 0.85);
      let ry = baseR * (1 - v * 0.75);
      let yc = y0;
      let z = z0 + v * L;
      switch (s.beak) {
        case 'hook':
        case 'falcon':
        case 'owl':
        case 'vulture': {
          // Strongly curved down-hooked raptor bill.
          const curve = Math.pow(v, 2.2) * L * 0.75;
          yc -= curve;
          z = z0 + Math.sin(v * 1.2) / Math.sin(1.2) * L * 0.85;
          ry *= 1.15;
          break;
        }
        case 'goose':
          rx = baseR * (0.85 - v * 0.35);
          ry = baseR * (0.75 - v * 0.55);
          yc -= v * L * 0.12;
          break;
        case 'pelican': {
          rx = baseR * 0.55 * (1 - v * 0.3);
          ry = baseR * (0.45 + 0.55 * Math.sin(Math.PI * Math.min(1, v * 1.1))) * (1 - v * 0.4);
          yc -= ry * 0.6;
          break;
        }
        case 'spear':
          rx = baseR * (1 - v * 0.95);
          ry = baseR * (1 - v * 0.9);
          break;
      }
      b.vert(Math.sin(a) * rx, yc + Math.cos(a) * ry, z, v, u, PART.BEAK, 4);
    });
  }

  /** Applies wing, tail, leg and head articulation for this frame. */
  update(p: BirdPose) {
    const out = this.posAttr.array as Float32Array;
    const rest = this.rest;
    const L = this.layout;
    const sh = this.shape;
    const v = this.tmp;
    const n = this.kind.length;
    const wristX = L.rootX + L.wristS * L.semi;
    const tailSpread = 0.55 + p.tailSpread * 1.4;
    for (let i = 0; i < n; i++) {
      const k = this.kind[i];
      if (k === 0) continue;
      const o = i * 3;
      let x = rest[o];
      let y = rest[o + 1];
      let z = rest[o + 2];
      if (k === 1) {
        const sd = this.side[i];
        const s = this.span[i];
        // Work in a right-wing frame: lx outward from the wrist, lz forward.
        const wHand = smooth(L.wristS - 0.08, L.wristS + 0.08, s);
        let lx = Math.abs(x) - wristX;
        let lz = z - L.wristZ;
        let ly = y;
        if (wHand > 0) {
          // Hand folds back around the wrist, then flexes up/down at it.
          const handFold = (p.fold * 2.2 + p.sweep * 0.9) * wHand;
          const c = Math.cos(handFold);
          const sn = Math.sin(handFold);
          const nx = lx * c + lz * sn;
          const nz = -lx * sn + lz * c;
          lx = nx;
          lz = nz;
          const wr = p.wrist * wHand;
          const hx = Math.max(lx, 0);
          ly += hx * Math.sin(wr);
          lx += hx * (Math.cos(wr) - 1);
        }
        // Arm: sweep/fold about the shoulder, elbow flexion shortens the span.
        let ax = (lx + wristX - L.rootX) * (1 - p.fold * 0.4);
        lz += L.wristZ - L.shoulderZ;
        const armFold = p.fold * 1.2 + p.sweep;
        const ca = Math.cos(armFold);
        const sa = Math.sin(armFold);
        const fx = ax * ca + lz * sa;
        lz = -ax * sa + lz * ca;
        ax = fx;
        // Feather twist (pitch) grows toward the tip.
        const twist = p.twist * s;
        const ct = Math.cos(twist);
        const st = Math.sin(twist);
        const ty = ly * ct + lz * st;
        const tz = lz * ct - ly * st;
        // Elevation: flap + dihedral (+ slight asymmetry when banking).
        const elev = p.flap + sh.dihedral * (1 - p.fold) + sd * p.bank * 0.12;
        const ce = Math.cos(elev);
        const se = Math.sin(elev);
        x = sd * (L.rootX + ax * ce - ty * se);
        y = ax * se + ty * ce;
        z = tz + L.shoulderZ;
      } else if (k === 2) {
        const dz = z - this.tailBaseZ;
        x = x * tailSpread;
        // Pitch around the tail base.
        const cp = Math.cos(p.tailPitch);
        const sp = Math.sin(p.tailPitch);
        const ny = (y - this.tailBaseY) * cp - dz * sp;
        const nz = dz * cp + (y - this.tailBaseY) * sp;
        // Twist (roll) for steering.
        const ct = Math.cos(p.tailTwist);
        const st = Math.sin(p.tailTwist);
        const rx = x * ct - ny * st;
        const ry = x * st + ny * ct;
        x = rx;
        y = ry + this.tailBaseY;
        z = nz + this.tailBaseZ;
      } else if (k === 3) {
        // Swing legs down from the hip for landing.
        const ang = p.legsDown * (sh.legs === 'trailing' ? 1.2 : 1.45);
        // Tucked raptor feet retract into the belly feathers until lowered.
        const ext = sh.legs === 'trailing' ? 1 : 0.15 + 0.85 * p.legsDown;
        const dy = (y - this.legPivot.y) * ext;
        const dz = (z - this.legPivot.z) * ext;
        const c = Math.cos(ang);
        const sn = Math.sin(ang);
        y = this.legPivot.y + dy * c + dz * sn;
        z = this.legPivot.z + dz * c - dy * sn;
      } else if (k === 4) {
        const ang = p.headYaw;
        const dx = x - this.headPivot.x;
        const dz = z - this.headPivot.z;
        const c = Math.cos(ang);
        const sn = Math.sin(ang);
        x = this.headPivot.x + dx * c + dz * sn;
        z = this.headPivot.z - dx * sn + dz * c;
      }
      v.set(x, y, z);
      out[o] = v.x;
      out[o + 1] = v.y;
      out[o + 2] = v.z;
    }
    this.posAttr.needsUpdate = true;
    this.geometry.computeVertexNormals();
  }
}
