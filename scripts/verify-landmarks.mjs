// Checks a town's landmark registry against its sources.
//
//   node scripts/verify-landmarks.mjs [town]      (default: princeton)
//
// For every landmark: the lat/lon -> world -> lat/lon round trip, the distance
// from the source OSM element to the building the game puts it on, whether the
// footprint contains that point, and the footprint's provenance. Writes
// docs/landmarks-<town>.md and exits non-zero when anything drifts too far.

import fs from 'node:fs/promises';
import path from 'node:path';
import { latLonToLocal, localToLatLon } from './lib/geo.mjs';

const id = process.argv[2] || 'princeton';
const town = JSON.parse(await fs.readFile(`public/data/${id}.json`, 'utf8'));
const cache = JSON.parse(await fs.readFile(path.join('.cache/osm', `${id}_${town.size}.json`), 'utf8'));
const byRef = new Map(cache.elements.map((e) => [`${e.type}/${e.id}`, e]));

const ringOf = (b) => {
  const r = [];
  for (let i = 0; i < b.p.length; i += 2) r.push([b.p[i], b.p[i + 1]]);
  return r;
};
const inside = (pts, x, z) => {
  let c = false;
  for (let i = 0, j = pts.length - 1; i < pts.length; j = i++) {
    const [xi, zi] = pts[i], [xj, zj] = pts[j];
    if (zi > z !== zj > z && x < ((xj - xi) * (z - zi)) / (zj - zi) + xi) c = !c;
  }
  return c;
};
const edgeDist = (pts, x, z) => {
  let d = Infinity;
  for (let i = 0; i < pts.length; i++) {
    const [ax, az] = pts[i], [bx, bz] = pts[(i + 1) % pts.length];
    const ex = bx - ax, ez = bz - az;
    const t = Math.max(0, Math.min(1, ((x - ax) * ex + (z - az) * ez) / (ex * ex + ez * ez || 1)));
    d = Math.min(d, Math.hypot(ax + ex * t - x, az + ez * t - z));
  }
  return d;
};

const rows = [];
let bad = 0;
for (const l of town.landmarks ?? []) {
  const b = town.buildings.find((q) => q.id === l.id);
  const ring = ringOf(b);
  const back = latLonToLocal(l.lat, l.lon);
  const roundTrip = Math.hypot(back.x - l.x, back.z - l.z);
  const ref = l.src.replace(/^osm:/, '');
  const e = byRef.get(ref);
  let srcPt = null;
  if (e?.type === 'node') srcPt = latLonToLocal(e.lat, e.lon);
  else if (e?.geometry) {
    const g = e.geometry.map((p) => latLonToLocal(p.lat, p.lon));
    srcPt = { x: g.reduce((s, p) => s + p.x, 0) / g.length, z: g.reduce((s, p) => s + p.z, 0) / g.length };
  }
  const offset = srcPt ? Math.hypot(srcPt.x - l.x, srcPt.z - l.z) : NaN;
  const contains = srcPt ? inside(ring, srcPt.x, srcPt.z) : false;
  const gap = srcPt && !contains ? edgeDist(ring, srcPt.x, srcPt.z) : 0;
  const ll = srcPt ? localToLatLon(srcPt.x, srcPt.z) : null;
  const ok = roundTrip < 0.5 && !!e && gap < 25;
  if (!ok) bad++;
  rows.push({ ...l, roundTrip, offset, contains, gap, srcLat: ll?.lat, srcLon: ll?.lon, ok });
}

const f = (n, d = 1) => (Number.isFinite(n) ? n.toFixed(d) : '—');
const md = [
  `# ${town.name} landmark verification`,
  '',
  `Generated by \`node scripts/verify-landmarks.mjs ${id}\`. Buildings: ${town.buildings.length} (${town.buildings.filter((b) => b.s).length} Microsoft ML footprints, the rest OpenStreetMap).`,
  '',
  '| id | name | source | footprint | lat, lon | world x, z | round trip (m) | source → model (m) | inside | confidence | status |',
  '|---|---|---|---|---|---|---|---|---|---|---|',
  ...rows.map(
    (r) =>
      `| ${r.id} | ${r.name} | ${r.src} | ${r.footprint} | ${r.lat}, ${r.lon} | ${f(r.x)}, ${f(r.z)} | ${f(r.roundTrip, 3)} | ${f(r.offset)} | ${r.contains ? 'yes' : `no (${f(r.gap)} m)`} | ${r.conf} | ${r.ok ? 'ok' : 'CHECK'} |`,
  ),
  '',
  '## Fidelity notes',
  '',
  ...rows.map((r) => `- **${r.name}** — ${r.fidelity}`),
  '',
];
await fs.mkdir('docs', { recursive: true });
await fs.writeFile(`docs/landmarks-${id}.md`, md.join('\n'));
for (const r of rows)
  console.log(`${r.ok ? '✓' : '✗'} ${r.id.padEnd(10)} round trip ${f(r.roundTrip, 3)} m · source→model ${f(r.offset)} m · ${r.contains ? 'inside' : `outside by ${f(r.gap)} m`} · conf ${r.conf}`);
console.log(`wrote docs/landmarks-${id}.md`);
process.exit(bad ? 1 : 0);
